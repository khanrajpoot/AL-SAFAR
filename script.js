// ===== Testimonial slider =====
let currentTestimonial = 0;
let testimonialTimer;

function showTestimonial(index) {
    const cards = document.querySelectorAll('.testimonial-card');
    const dots = document.querySelectorAll('.dot');

    cards.forEach(c => c.classList.remove('active'));
    dots.forEach(d => d.classList.remove('active'));

    currentTestimonial = (index + cards.length) % cards.length;
    cards[currentTestimonial].classList.add('active');
    dots[currentTestimonial].classList.add('active');
}

function autoSlide() {
    clearInterval(testimonialTimer);
    testimonialTimer = setInterval(() => showTestimonial(currentTestimonial + 1), 5000);
}

// ===== Animated counters =====
function animateCounters() {
    const counters = document.querySelectorAll('[data-count]');
    counters.forEach(counter => {
        const target = parseInt(counter.dataset.count);
        const duration = 2000;
        const startTime = performance.now();

        function update(now) {
            const progress = Math.min((now - startTime) / duration, 1);
            const ease = 1 - Math.pow(1 - progress, 3);
            counter.textContent = Math.floor(ease * target).toLocaleString() + (counter.dataset.count === '98' ? '%' : '+');
            if (progress < 1) {
                requestAnimationFrame(update);
            }
        }
        requestAnimationFrame(update);
    });
}

